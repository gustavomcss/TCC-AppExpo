import assert from "node:assert/strict";
import { after, before, describe, test } from "node:test";
import { login } from "./helpers/client.js";
import { complaintForm, createFactories } from "./helpers/factories.js";
import { startPocketBase } from "./helpers/pocketbase.js";

/*
 * API tests for the I-03 collections. The acceptance criteria of the issue are the describe
 * blocks below. Enum values (motorista, carro, aberta...) are data of the model, so they stay
 * in Portuguese.
 */

/** Fields each collection must have, as in the ER diagram. */
const DER = {
    users: ["name", "photo", "role", "active", "created"],
    vehicles: ["plate", "active", "type", "model", "odometer", "created"],
    routes: ["user", "vehicle", "status", "itinerary", "date_departure", "km_departure", "obs_departure", "date_return", "km_return", "obs_return"],
    complaints: ["route_current", "route_previous", "created", "km_complaint", "status", "photo", "reviewed"],
    fuels: ["user", "vehicle", "created", "km_fuel", "type", "liters", "cost"],
    oils: ["user", "vehicle", "created", "km_oil", "type", "cost"],
    repairs: ["user", "vehicle", "created", "km_repair", "description", "cost"],
};

/** A creation date a client could try to force; the server must ignore it. */
const OLD_DATE = "2000-01-01 00:00:00.000Z";

/** True when a PocketBase date is within a minute of now, i.e. it was generated by the server. */
const isServerDate = (value) => Math.abs(Date.parse(value.replace(" ", "T")) - Date.now()) < 60_000;

/* State shared by the file: one disposable instance, plus users and a vehicle that tests may reuse. */
let pb;
let admin;
let make;
let motorista;
let supervisor;
let vehicle;

/* Starts the instance and creates the shared users and vehicle. */
before(async () => {
    pb = await startPocketBase();
    admin = pb.admin;
    make = createFactories(admin);
    motorista = await make.user();
    supervisor = await make.user({ role: "supervisor" });
    vehicle = await make.vehicle();
});

/* Stops the instance and removes its temp folder. */
after(() => pb?.stop());

describe("the 7 collections exist with the fields, enums and relations of the ER diagram", () => {
    test("collections and fields", async () => {
        const { body } = await admin.get("/api/collections?perPage=100");
        const fieldsByCollection = Object.fromEntries(body.items.map((c) => [c.name, c.fields.map((f) => f.name)]));

        for (const [name, expected] of Object.entries(DER)) {
            assert.ok(fieldsByCollection[name], `collection ${name} does not exist`);
            const missing = expected.filter((field) => !fieldsByCollection[name].includes(field));
            assert.deepEqual(missing, [], `missing fields in ${name}`);
        }
    });

    test("enums reject values outside the ER diagram", async () => {
        const route = await make.route({ user: motorista, vehicle });
        const cases = [
            ["users", "role", { email: "enum@test.local", password: "senha12345", passwordConfirm: "senha12345", name: "E", role: "admin" }],
            ["vehicles", "type", { plate: "ENU-0001", type: "trator", model: "M", odometer: 1 }],
            ["routes", "status", { user: motorista.id, vehicle: vehicle.id, status: "pausada", itinerary: "i", km_departure: 1 }],
            ["fuels", "type", { user: motorista.id, vehicle: vehicle.id, km_fuel: 1, type: "alcool", liters: 1, cost: 1 }],
        ];
        for (const [collection, field, data] of cases) {
            const response = await admin.post(`/api/collections/${collection}/records`, data);
            assert.equal(response.status, 400, `${collection}.${field}`);
            assert.ok(response.body.data[field], `${collection}.${field} should have an error`);
        }

        const complaint = await admin.post("/api/collections/complaints/records", complaintForm({ route_current: route.id, status: "arquivada" }));
        assert.equal(complaint.status, 400);
        assert.ok(complaint.body.data.status);
    });

    test("creates one record of each collection", async () => {
        const previous = await make.route({ user: motorista, vehicle, status: "finalizada", km_return: 1100 });
        const current = await make.route({ user: motorista, vehicle });
        const records = {
            users: supervisor,
            vehicles: vehicle,
            routes: current,
            complaints: await make.complaint({ route_current: current.id, route_previous: previous.id }),
            fuels: await make.fuel({ user: motorista, vehicle }),
            oils: await make.oil({ user: motorista, vehicle }),
            repairs: await make.repair({ user: motorista, vehicle }),
        };
        for (const [collection, record] of Object.entries(records)) {
            assert.ok(record.id, `${collection} record`);
        }
    });

    test("plate is unique", async () => {
        const created = await make.vehicle({ plate: "ABC-1D23" });
        const duplicate = await admin.post("/api/collections/vehicles/records", { plate: "ABC-1D23", type: "moto", model: "X", odometer: 1 });
        assert.equal(created.plate, "ABC-1D23");
        assert.equal(duplicate.status, 400);
        assert.equal(duplicate.body.data.plate.code, "validation_not_unique");
    });

    test("route_current is unique in complaints", async () => {
        const route = await make.route({ user: motorista, vehicle });
        await make.complaint({ route_current: route.id });
        const duplicate = await admin.post("/api/collections/complaints/records", complaintForm({ route_current: route.id, km_complaint: 991 }));
        assert.equal(duplicate.status, 400);
        assert.ok(duplicate.body.data.route_current);
    });

    test("the complaint photo is required", async () => {
        const route = await make.route({ user: motorista, vehicle });
        const response = await admin.post("/api/collections/complaints/records", complaintForm({ route_current: route.id, photo: null }));
        assert.equal(response.status, 400);
        assert.ok(response.body.data.photo);
    });
});

describe("no relation has cascade delete (RB12, RB18)", () => {
    test("every relation has cascadeDelete off", async () => {
        const { body } = await admin.get("/api/collections?perPage=100");
        const relations = body.items.flatMap((c) => c.fields.filter((f) => f.type === "relation").map((f) => ({ ...f, collection: c.name })));

        assert.equal(relations.length, 10, "expected 10 relations in the ER diagram");
        for (const relation of relations) {
            assert.equal(relation.cascadeDelete, false, `${relation.collection}.${relation.name}`);
        }
    });

    test("a vehicle without links can be deleted", async () => {
        const free = await make.vehicle();
        assert.equal((await admin.delete(`/api/collections/vehicles/records/${free.id}`)).status, 204);
    });

    test("a vehicle with linked records is not deleted", async () => {
        const used = await make.vehicle();
        await make.fuel({ user: motorista, vehicle: used });
        assert.equal((await admin.delete(`/api/collections/vehicles/records/${used.id}`)).status, 400);
        assert.equal((await admin.get(`/api/collections/vehicles/records/${used.id}`)).status, 200);
    });

    test("a user with linked records is not deleted", async () => {
        const driver = await make.user();
        await make.route({ user: driver, vehicle });
        assert.equal((await admin.delete(`/api/collections/users/records/${driver.id}`)).status, 400);
        assert.equal((await admin.get(`/api/collections/users/records/${driver.id}`)).status, 200);
    });

    test("a route with a complaint is not deleted", async () => {
        const route = await make.route({ user: motorista, vehicle });
        await make.complaint({ route_current: route.id });
        assert.equal((await admin.delete(`/api/collections/routes/records/${route.id}`)).status, 400);
    });
});

describe("decimal fields follow the 8,2 pattern (RB16)", () => {
    test("rejects more than two decimal places", async () => {
        const cases = [
            ["vehicles", "odometer", { plate: "DEC-0001", type: "carro", model: "M", odometer: 10.123 }],
            ["routes", "km_departure", { user: motorista.id, vehicle: vehicle.id, status: "aberta", itinerary: "i", km_departure: 5.001 }],
            ["fuels", "liters", { user: motorista.id, vehicle: vehicle.id, km_fuel: 1, type: "etanol", liters: 1.005, cost: 1 }],
            ["repairs", "cost", { user: motorista.id, vehicle: vehicle.id, km_repair: 1, description: "d", cost: 0.999 }],
        ];
        for (const [collection, field, data] of cases) {
            const response = await admin.post(`/api/collections/${collection}/records`, data);
            assert.equal(response.status, 400, `${collection}.${field}`);
            assert.equal(response.body.data[field].code, "validation_too_many_decimals", `${collection}.${field}`);
        }
    });

    test("rejects negative values or values above 999,999.99", async () => {
        const negative = await admin.post("/api/collections/fuels/records", { user: motorista.id, vehicle: vehicle.id, km_fuel: 1, type: "etanol", liters: 1, cost: -1 });
        const tooBig = await admin.post("/api/collections/oils/records", { user: motorista.id, vehicle: vehicle.id, km_oil: 1, type: "x", cost: 1000000 });
        assert.equal(negative.status, 400);
        assert.ok(negative.body.data.cost);
        assert.equal(tooBig.status, 400);
        assert.ok(tooBig.body.data.cost);
    });

    test("accepts two decimal places and the maximum value", async () => {
        await make.fuel({ user: motorista, vehicle, km_fuel: 0.1, liters: 0.3, cost: 1234.56 });
        const repair = await make.repair({ user: motorista, vehicle, cost: 999999.99 });
        assert.equal(repair.cost, 999999.99);
    });

    test("the rule also applies on update", async () => {
        const target = await make.vehicle();
        const response = await admin.patch(`/api/collections/vehicles/records/${target.id}`, { odometer: 1000.555 });
        assert.equal(response.status, 400);
        assert.ok(response.body.data.odometer);
    });
});

describe("created is generated by the server and a sent value is ignored (RNF05)", () => {
    test("superuser sends an old date", async () => {
        const route = await make.route({ user: motorista, vehicle, date_departure: OLD_DATE });
        const records = {
            vehicles: await make.vehicle({ created: OLD_DATE }),
            fuels: await make.fuel({ user: motorista, vehicle, created: OLD_DATE }),
            oils: await make.oil({ user: motorista, vehicle, created: OLD_DATE }),
            repairs: await make.repair({ user: motorista, vehicle, created: OLD_DATE }),
            complaints: await make.complaint({ route_current: route.id, created: OLD_DATE }),
        };
        for (const [collection, record] of Object.entries(records)) {
            assert.ok(isServerDate(record.created), `${collection}.created = ${record.created}`);
        }
        assert.ok(isServerDate(route.date_departure), `routes.date_departure = ${route.date_departure}`);
    });

    test("regular user sends an old date", async () => {
        const asMotorista = await login(pb.url, "users", motorista.email, motorista.password);
        const response = await asMotorista.post("/api/collections/oils/records", {
            user: motorista.id,
            vehicle: vehicle.id,
            km_oil: 1,
            type: "x",
            cost: 1,
            created: OLD_DATE,
        });
        assert.equal(response.status, 200);
        assert.ok(isServerDate(response.body.created), response.body.created);
    });
});

describe("user rules that hold at every stage (RB19)", () => {
    test("there is no self sign-up", async () => {
        const response = await pb.anonymous.post("/api/collections/users/records", {
            email: "auto@test.local",
            password: "senha12345",
            passwordConfirm: "senha12345",
            name: "Auto",
            role: "supervisor",
            active: true,
        });
        assert.ok([400, 403].includes(response.status), `status ${response.status}`);
    });

    test("a driver cannot change their own role", async () => {
        const driver = await make.user();
        const asDriver = await login(pb.url, "users", driver.email, driver.password);
        const response = await asDriver.patch(`/api/collections/users/records/${driver.id}`, { role: "supervisor" });
        assert.ok([400, 403, 404].includes(response.status), `status ${response.status}`);
        assert.equal((await admin.get(`/api/collections/users/records/${driver.id}`)).body.role, "motorista");
    });
});
